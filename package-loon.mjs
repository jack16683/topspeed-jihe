// Build, test and package the plain plugin without network access or private inputs.
import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import './build-loon.mjs';
const version='2.1.1',entry='loon/极速鸡盒.plugin';
const base='https://raw.githubusercontent.com/jack16683/topspeed-jihe/';
const runtime=base+'v'+version+'/';
const source=fs.readFileSync(entry,'utf8');
assert.match(source,/^#!name = 极速鸡盒$/m);
assert.match(source,/^#!desc = 知道你的鸡盒到底有多快$/m);
assert.match(source,/^#!author = jack16683$/m);
const references=[...source.matchAll(/\bscript\("([^\"]+)"/g)].map(m=>m[1]);
assert.equal(references.length,3);
const scripts=[...new Set(references)];
assert.deepEqual(scripts,[runtime+'loon/scripts/ride-fill.js',runtime+'loon/scripts/cache-tools.js']);
const digest=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const remoteScripts=scripts.map(url=>{const path=url.slice(runtime.length);assert.ok(fs.statSync(path).isFile());return {url,path,sha256:digest(path)};});
const checks=spawnSync(process.execPath,['--test','--test-reporter=tap','loon/tests/engine.test.mjs','loon/tests/ride-fill.test.mjs'],{encoding:'utf8'});
if(checks.status!==0)throw new Error(checks.stdout+'\n'+checks.stderr);
const count=checks.stdout.match(/^# tests (\d+)$/m),passed=checks.stdout.match(/^# pass (\d+)$/m);
assert.ok(count&&passed);assert.equal(count[1],passed[1]);
fs.mkdirSync('outputs',{recursive:true});
const report={format:'plain-plugin',version,author:'jack16683',plugin:{path:entry,url:base+'main/loon/'+encodeURIComponent('极速鸡盒.plugin')+'?v='+version,sha256:digest(entry)},remoteScripts,offlineTests:Number(count[1]),cachePolicy:'algorithm-versioned; reuse known, zero and unknown; recompute old-version rides once',deviceValidated:false};
fs.writeFileSync('outputs/validation.json',JSON.stringify(report,null,2)+'\n');
const files=['README.md','LICENSE','NOTICE','build-loon.mjs','package-loon.mjs','loon/README.md','loon/LICENSE',entry,'loon/src/ride-engine.js','loon/src/ride-handler.js','loon/scripts/ride-fill.js','loon/scripts/cache-tools.js','loon/tests/engine.test.mjs','loon/tests/ride-fill.test.mjs'];
const archive='outputs/极速鸡盒-source.zip';
const python="from pathlib import Path\nimport sys,json,zipfile\nfiles=json.loads(sys.argv[1]); target=sys.argv[2]\nwith zipfile.ZipFile(target,'w',zipfile.ZIP_DEFLATED) as z:\n for f in files:z.write(f,'极速鸡盒/'+f)\nwith zipfile.ZipFile(target) as z:\n assert z.testzip() is None\n for f in files:assert z.read('极速鸡盒/'+f)==Path(f).read_bytes()\n";
const result=spawnSync('python3',['-c',python,JSON.stringify(files),archive],{encoding:'utf8'});
if(result.error)throw result.error;assert.equal(result.status,0,result.stderr);
console.log(JSON.stringify({format:report.format,version,author:report.author,tests:report.offlineTests,remoteScripts:scripts.length,sourceFiles:files.length,pluginSHA256:report.plugin.sha256}));
